#!/usr/bin/env python3
"""Compile preparation-only source/family lookup from installed closed metadata.

This table chooses which existing gate to verify; it cannot admit an activity.
Run against one exact installed Resources root. All inputs are pinned in output.
"""
import argparse
import hashlib
import json
from pathlib import Path

PACKAGES = [
    ("Manual", "typed-manual-tasks-v1/manifest.json"),
    ("Manual", "compiled-manual-families-v1/manifest.json"),
    ("Recipe", "compiled-recipe-families-v1/level068/manifest.json"),
    ("Advanced", "compiled-recipe-families-v1/advanced/manifest.json"),
    ("Graph", "compiled-recipe-families-v1/manual-procedure-graph/manifest.json"),
    ("Ordered", "compiled-manual-families-v1/ordered-contact/manifest.json"),
    ("Physical", "compiled-manual-families-v1/physical-contact/manifest.json"),
    ("Piecewise", "compiled-manual-families-v1/piecewise-contact/manifest.json"),
    ("Harmonic", "compiled-manual-families-v1/harmonic-contact/manifest.json"),
    ("Source", "compiled-manual-families-v1/source-contact/manifest.json"),
    ("Extra", "compiled-extra-source17/manifest.json"),
    ("Ear", "compiled-manual-families-v1/ear234/closed-package.json"),
    ("C43", "compiled-manual-families-v1/c43/closed-package.json"),
]


def compile_routes(root: Path) -> str:
    if not root.is_absolute() or root.is_symlink() or root.resolve() != root:
        raise ValueError("exact absolute Resources directory required")
    routes, pins = {}, []

    def read(relative):
        rel = Path(relative)
        if rel.is_absolute() or any(part in {".", ".."} for part in rel.parts) or rel.as_posix() != relative:
            raise ValueError("closed package relative path required")
        path = root / relative
        if any(p.is_symlink() for p in [path, *path.parents]) or not path.is_file():
            raise ValueError("real input file required")
        raw = path.read_bytes()
        pins.append(f"// {relative}: {len(raw)}B SHA256 {hashlib.sha256(raw).hexdigest()}")
        return raw

    for family, relative in PACKAGES:
        data = json.loads(read(relative))
        identities = {}
        if family in {"Graph", "Extra"}:
            pin = data.get("bulk_definitions", data.get("definitions"))
            path = str(Path(relative).parent / pin["path"])
            raw = read(path)
            if len(raw) != pin["bytes"] or hashlib.sha256(raw).hexdigest() != pin["sha256"]:
                raise ValueError("closed definitions pin mismatch")
            rows = [json.loads(line) for line in raw.splitlines()]
            keys = [row["source_key"] for row in rows]
            identities = {row["source_key"]: row["source_identity"] for row in rows}
            if "source_keys" in data and keys != data["source_keys"]:
                raise ValueError("manifest/definition exact key order differs")
        elif "source_keys" in data:
            keys = data["source_keys"]
        elif "source_key" in data:
            # The representative's manifest key differs from its source identity.
            keys = ["exercise-completeness-r01/level053/moduleb/p003-t1-r1-c2/cmajrp"]
        elif isinstance(data.get("rows"), list):
            keys = [row["source_key"] for row in data["rows"]]
            identities = {row["source_key"]: row["source_identity"] for row in data["rows"]}
        else:
            pin = data["definitions"]
            path = str(Path(relative).parent / pin["path"])
            raw = read(path)
            if len(raw) != pin["bytes"] or hashlib.sha256(raw).hexdigest() != pin["sha256"]:
                raise ValueError("closed definitions pin mismatch")
            rows = [json.loads(line) for line in raw.splitlines()]
            keys = [row["source_key"] for row in rows]
            identities = {row["source_key"]: row["source_identity"] for row in rows}
        for key in keys:
            prefix = "exercise-completeness-r01/"
            if key not in identities and not key.startswith(prefix):
                raise ValueError(f"unrecognized key namespace: {family}, {key!r}")
            source = identities.get(key, key[len(prefix):])
            if source == "level053/moduleb/p003-t1-r1-c2/cmajrp" and routes.get(source) == "Manual" and family == "Graph":
                # Existing Home resolves the adopted Graph before legacy Manual.
                routes[source] = family
                pins.append("// Reviewed legacy overlap: Level53 CmajRP resolves Graph before Manual, matching Home.")
                continue
            if not source or source in routes:
                raise ValueError(f"duplicate/empty identity: {source!r}, {routes.get(source)!r}, {family!r}")
            routes[source] = family
    lines = ["#pragma once", "#include <algorithm>", "#include <iterator>", "#include <string_view>",
             "// GENERATED by Tools/generate_source_task_routes.py; preparation routing only.", *pins,
             "namespace fathom::desktop::source_routes {",
             "enum class Family { All, None, Manual, Recipe, Advanced, Graph, Ordered, Physical, Piecewise, Harmonic, Source, Extra, Ear, C43 };",
             "struct Route { std::string_view source; Family family; };", "inline constexpr Route routes[]{"]
    lines.extend(f"    {{{json.dumps(source)},Family::{family}}}," for source, family in sorted(routes.items()))
    lines += ["};", "inline Family familyFor(std::string_view source) {",
              "    const auto found=std::lower_bound(std::begin(routes),std::end(routes),source,",
              "        [](const Route& row,std::string_view value){return row.source<value;});",
              "    return found!=std::end(routes)&&found->source==source?found->family:Family::None;", "}", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("resources", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = compile_routes(args.resources)
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit("generated route table differs")
    else:
        args.output.write_text(result)
