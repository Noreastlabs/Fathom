inline bool isSourceKey(std::string_view value) {
    return value.rfind("exercise-completeness-r01/", 0) == 0 ||
           value.rfind("proposed-printed-", 0) == 0;
}
inline std::string title(std::string_view key) {
    const auto found = std::lower_bound(entries.begin(), entries.end(), key,
        [](const Entry& entry, std::string_view wanted) { return entry.key < wanted; });
    if(found == entries.end() || found->key != key)
        throw std::runtime_error("Unknown printed source choice");
    return std::string(found->title);
}
inline json::Value projectEnumLabels(json::Value schema) {
    if(!schema.isObject()) return schema;
    const auto* choices = schema.find("enum");
    if(!choices || !choices->isArray()) return schema;
    bool sourceChoice = false;
    for(const auto& choice : choices->array())
        if(choice.isString() && isSourceKey(choice.string())) {
            (void) title(choice.string());
            sourceChoice = true;
        }
    if(!sourceChoice) return schema;
    // An already projected native label remains exact, including B72 key names.
    if(const auto* labels = schema.find("enumLabels")) {
        if(!labels->isArray() || labels->array().size() != choices->array().size())
            throw std::runtime_error("Printed source choice label cardinality");
        for(const auto& label : labels->array())
            if(!label.isString() || label.string().empty() || isSourceKey(label.string()))
                throw std::runtime_error("Invalid printed source choice label");
        return schema;
    }
    json::Value::Array labels;
    for(const auto& choice : choices->array()) {
        if(choice.null()) labels.emplace_back("Unknown / not supplied");
        else if(choice.isString()) labels.emplace_back(isSourceKey(choice.string()) ?
            title(choice.string()) : choice.string());
        else throw std::runtime_error("Printed source choice value shape");
    }
    schema.object().emplace("enumLabels", std::move(labels));
    return schema;
}
